def fig1():
    fig, ax = page(
        "一条倒 V：从 12 万到 21 万，再回到 8 万",
        "碳酸锂期货主力合约与现货报价，2026 年内关键节点",
        source="来源：中国能源网 2026-11-26（援引南华期货研报及第一财经）。"
               "年初、9 月初为现货口径，5 月 13 日与 11 月 26 日为期货主力合约口径。",
        punch="从 5 月高点到 11 月低点，回撤约 61.6%。",
        foot="事实来源：碳酸锂主力合约 LC2701 2026-11-26 收 81,520 元/吨；"
             "5 月 13 日盘中最高 209,880 元/吨；现货年初约 12 万元/吨、9 月初约 15 万元/吨。")

    series = [(
        "元/吨",
        ["1 月初", "5 月 13 日", "9 月初", "11 月 26 日"],
        [120000, 209880, 150000, 81520],
        NAVY,
    )]
    lines(ax, series, x0=0.110, y0=0.330, w=0.620, h=0.350,
          show_values=True, value_fmt="{:,.0f}")

    card(ax, 0.045, 0.175, 0.900, 0.070, LIGHT, face=PALE)
    ax.text(0.068, 0.210, "口径提示：现货与期货、年初与年内的报价方式不同，"
                          "本图用于呈现方向与量级，不宜逐点相减。",
            fontsize=7.4, color=SLATE, ha="left", va="center", zorder=7)

    save(fig, "图1_价格回到起点")


